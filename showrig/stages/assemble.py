"""Assembly: build the editable FilmCraft project from the plan, then render it through FilmCraft.

Tracks: V1 Picture, V2 Titles, V3 Overlays (notes and images), A1 Voice, A2 Music, C1 Captions. Every clip is
named "<beat id> · <label>" and coloured by kind; a marker spans each scene; out/manifest.json records the beats.
A rebuild never overwrites by surprise: the previous project moves to out/versions/ first.
"""
from __future__ import annotations

import json
import shutil
import time
from pathlib import Path

from .. import tools
from ..project import Film, probe, run

TICKS = 254016000000  # FilmCraft time base, per second


class FilmCraft:
    def __init__(self, film: Film, project):
        self.film, self.project = film, project
        self.cli = tools.filmcraft()
        if not self.cli:
            raise SystemExit("assembly needs the FilmCraft CLI (set FILMCRAFT_CLI)")

    def ticks(self, seconds: float) -> int:
        """Snap to whole frames."""
        fps = self.film.fmt["fps"]
        return round(seconds * fps) * TICKS // fps

    def __call__(self, label: str, commands: list[dict], create: bool = False) -> list:
        """Run FilmCraft commands as one script; keep the script and its receipt; fail on any rejection."""
        script = self.film.log(f"fc-{label}.jsonl")
        script.write_text("".join(json.dumps(c) + "\n" for c in commands))
        opts = ["--save-as", self.project] if create else ["--project", self.project, "--save"]
        res = run([self.cli, "--compact", *opts, "run", script], self.film.log(f"fc-{label}.log"))
        rows = [json.loads(line) for line in res.stdout.splitlines() if line.startswith("{")]
        if len(rows) != len(commands) or not all(r.get("ok") for r in rows):
            bad = next((r for r in rows if not r.get("ok")), res.stderr[-800:])
            raise SystemExit(f"FilmCraft rejected {label}: {bad}")
        return [r["result"] for r in rows]


def cmd(cid: str, **params) -> dict:
    return {"id": cid, "params": params}


def project_path(film: Film):
    return film.out / f"{film.name}.fcproj"


# What each kind of beat is, how it looks in the project, and what an editor can do with it.
LABELS = {"footage": "Forest", "capture": "Cerulean", "stage": "Violet", "backdrop": "Tan", "title": "Mango",
          "image": "Rose", "note": "Lavender", "voice": "Iris", "voice-file": "Blue", "music": "Teal",
          "music-file": "Green"}
CLASSES = {"footage": "native", "voice-file": "native", "music-file": "native", "image": "native", "note": "native",
           "title": "editable in EffectCraft", "capture": "compiled", "stage": "compiled", "backdrop": "compiled",
           "voice": "compiled", "music": "compiled"}
BINS = {"footage": "Footage", "capture": "Captures", "stage": "3D stage", "backdrop": "Backdrops", "title": "Titles",
        "image": "Images", "voice": "Voice", "voice-file": "Voice", "music": "Music", "music-file": "Music"}
TRACKS = {"V1": "Picture", "V2": "Titles", "V3": "Overlays", "A1": "Voice", "A2": "Music"}
SCENE_COLORS = {"intro": "Violet", "outro": "Violet", "segment": "Forest", "card": "Tan", "credits": "Mango"}
PROMISE = ("Editable: the timeline (cut, timing, clips, voice, music, captions) is native FilmCraft, and titles are "
           "EffectCraft projects (out/../work/titles/*.ecproj). Compiled beats (3D stage, browser captures, backdrops, "
           "generated voice and score) are regenerated by Showrig from out/manifest.json, not edited inside. "
           "Clip names start with a stable beat id; keep it when you rename a clip so Showrig can follow your edits.")
REQUIRED = ["file.newProject", "file.newSequence", "file.import", "timeline.place", "effects.setParam",
            "sequence.applyVideoTransition", "clip.rename", "timeline.setTrack", "graphics.newText", "graphics.set",
            "captions.newTrack", "captions.setStyle", "captions.add", "captions.export", "markers.add",
            "file.newBin", "project.moveToBin", "file.exportOtio", "file.exportFcpxml",
            *sorted({f"edit.label.{c.lower()}" for c in [*LABELS.values(), *SCENE_COLORS.values()]})]


def check_capabilities(cli: str) -> dict:
    """Fail loudly, before building anything, when this FilmCraft lacks a command Showrig uses."""
    import subprocess
    version = subprocess.run([cli, "--version"], capture_output=True, text=True).stdout.strip()
    listed = subprocess.run([cli, "commands", "--json"], capture_output=True, text=True)
    try:
        have = {c["id"] for c in json.loads(listed.stdout)}
    except (ValueError, KeyError, TypeError):
        raise SystemExit(f"could not list {version or cli}'s commands: {listed.stderr.strip()[-300:]}")
    missing = [c for c in REQUIRED if c not in have]
    if missing:
        raise SystemExit(f"{version} lacks commands Showrig needs: {', '.join(missing)}")
    return {"version": version, "commands": len(have)}


def beat_label(film: Film, kind: str, e: dict | None) -> str:
    """The human half of a clip name."""
    scene = next((s for s in film.board["scenes"] if e and s["id"] == e.get("scene")), {})
    if kind in ("footage", "capture"):
        shot = scene["shots"][e["shot"] - 1]
        return Path(shot["file"]).name if shot.get("file") else "capture of " + Path(shot["capture"]["url"]).name
    if kind == "title":
        return scene.get("title") or "Credits"
    if kind in ("voice", "voice-file"):
        return e["text"] if len(e["text"]) <= 48 else e["text"][:47] + "…"
    if kind == "image":
        return Path(e["path"]).name
    if kind == "note":
        return e["text"]
    if kind in ("music", "music-file"):
        m = film.board["music"]
        return Path(m["file"]).name if kind == "music-file" else f"score ({m.get('mood', 'procedural')})"
    return {"stage": "3D stage", "backdrop": "backdrop"}[kind]


def intended(film: Film, plan: dict, music: str | None) -> list[dict]:
    """Every clip the plan asks for (notes excepted, they are graphics), as beats: id, kind, class, track, path
    and frames. A fresh build places all of them; reconcile places only the ones it may change."""
    fps = film.fmt["fps"]
    voice_kind = "voice-file" if film.board["voice"]["source"] == "files" else "voice"
    music_kind = "music-file" if film.board["music"]["source"] == "file" else "music"
    rows = [("V1", "capture" if c.get("capture") else c["kind"], c) for c in plan["video"]]
    rows += [("V2", "title", c) for c in plan["titles"]]
    rows += [("A1", voice_kind, n) for n in plan["narration"]]
    if music:
        rows.append(("A2", music_kind, {"id": "music", "scene": None, "path": music, "start_f": 0,
                                        "dur_f": round(probe(Path(music))["duration"] * fps)}))
    rows += [("V3", "image", i) for i in plan.get("images", [])]
    return [{"id": e["id"], "scene": e.get("scene"), "kind": kind, "class": CLASSES[kind], "track": track,
             "path": e["path"], "start_f": e["start_f"], "dur_f": e.get("dur_f"), "in_f": e.get("in_f", 0),
             "_entry": e} for track, kind, e in rows]


def place_cmds(beats: list[dict], items: dict, ft) -> list[dict]:
    """timeline.place for each beat, at its frames; sound clips keep their whole length."""
    out = []
    for b in beats:
        if b["track"].startswith("A"):
            out.append(cmd("timeline.place", item=items[b["path"]], track=b["track"], frame=b["start_f"],
                           video=False, insert=False))
        else:
            out.append(cmd("timeline.place", item=items[b["path"]], track=b["track"], frame=b["start_f"],
                           sourceIn=ft(b["in_f"]), duration=ft(b["dur_f"]), audio=False, insert=False))
    return out


def motion_cmds(film: Film, beats: list[dict], picture_order: list[dict], ft) -> list[dict]:
    """The push-in, the transition into each picture clip (chosen from the clip before it in picture_order,
    the whole V1 track), and the image fades, for the given placed beats."""
    w, h, fps = film.fmt["width"], film.fmt["height"], film.fmt["fps"]
    push, style = film.style["pushIn"], film.style["transitions"]
    order = [b["id"] for b in picture_order]
    entries = {b["id"]: b["_entry"] for b in picture_order}
    out = []
    for b in [b for b in beats if b["track"] == "V1"]:
        clip, c = b["clip"], b["_entry"]
        if c["push"]:  # keyframe times are sequence times
            out.append(cmd("effects.setParam", clip=clip, effect="motion", param="scale", value=100,
                           time=ft(c["start_f"]), keyframe=True))
            out.append(cmd("effects.setParam", clip=clip, effect="motion", param="scale", value=100 + push,
                           time=ft(c["start_f"] + c["dur_f"]), keyframe=True))
        i = order.index(b["id"])
        prev = entries[order[i - 1]] if i > 0 else None
        if prev is not None and style != "cuts":
            if style == "simple":
                effect, frames = "Cross Dissolve", 14
            elif c["kind"] == "footage" and prev["kind"] == "stage":
                effect, frames = "Cross Zoom", 20
            elif c["kind"] == "footage":
                effect, frames = "Cross Dissolve", 14
            else:
                effect, frames = "Film Dissolve", 24
            out.append(cmd("sequence.applyVideoTransition", clip=clip, effect=effect,
                           frames=round(frames * fps / 60), edge="in"))
    # Images sit left of their title, fitted into the space the title leaves them (a 660 px avatar
    # fills its height): a fade in and out and a slow push, all editable keyframes.
    for b in [b for b in beats if b["kind"] == "image"]:
        clip, i = b["clip"], b["_entry"]
        a, z = i["start_f"], i["start_f"] + i["dur_f"]
        dims = probe(Path(i["path"]))
        size = min(0.34 * w / dims["width"], 0.584 * h / dims["height"]) * 100
        out += [cmd("effects.setParam", clip=clip, effect="motion", param="position", value=[round(w * .25), round(h / 2)]),
                cmd("effects.setParam", clip=clip, effect="motion", param="scale", value=round(size, 2),
                    time=ft(a), keyframe=True),
                cmd("effects.setParam", clip=clip, effect="motion", param="scale", value=round(size * 1.04, 2),
                    time=ft(z), keyframe=True)]
        out += [cmd("effects.setParam", clip=clip, effect="opacity", param="opacity", value=v, time=ft(at),
                    keyframe=True) for at, v in ((a, 0), (a + round(.6 * fps), 100), (z - round(.5 * fps), 100), (z, 0))]
    return out


def name_cmds(film: Film, beats: list[dict]) -> list[dict]:
    """Clip names ("<id> · <label>") and colour labels by kind; sets each beat's "name"."""
    out, by_color = [], {}
    for b in beats:
        b["name"] = f"{b['id']} · {beat_label(film, b['kind'], b['_entry'])}"
        out.append(cmd("clip.rename", clip=b["clip"], name=b["name"]))
        by_color.setdefault(LABELS[b["kind"]], []).append(b["clip"])
    return out + [cmd(f"edit.label.{color.lower()}", clips=clips) for color, clips in sorted(by_color.items())]


def make_notes(film: Film, fc: FilmCraft, notes: list[dict], ft) -> list[dict]:
    """On-screen notes are FilmCraft text graphics; returns them as beats."""
    w, h = film.fmt["width"], film.fmt["height"]
    scale, out = min(w / 1920, h / 1080), []
    for note in notes:
        made = fc(f"06-note-{note['scene']}", [cmd("graphics.newText", text=note["text"],
                                                   position=[w - 50 * scale, 64 * scale], size=round(26 * scale),
                                                   font="Inter", seconds=note["duration"], track=2,
                                                   time=ft(note["start_f"]), newClip=True)])[0]
        fc(f"06-note-{note['scene']}-style", [cmd("graphics.set", clip=made["clip"], layer=0,
                                                  props={"align": "right", "fill_color": "#e8eef5", "background": True,
                                                         "shadow": True, "opacity": 88})])
        out.append({"id": note["id"], "scene": note["scene"], "kind": "note", "class": CLASSES["note"], "track": "V3",
                    "clip": made["clip"], "item": None, "path": None, "start_f": note["start_f"],
                    "dur_f": note["dur_f"], "in_f": 0, "_entry": note})
    return out


def caption_cmds(film: Film, plan: dict) -> list[dict]:
    w, h, fps = film.fmt["width"], film.fmt["height"], film.fmt["fps"]
    out = [cmd("captions.newTrack", format="Subtitle", name="Captions", language="en"),
           cmd("captions.setStyle", track="C1", font="Inter", size=round(34 * min(1, w / h)), color="#ffffff",
               background=True, backgroundColor="#000000b0", align="center", anchor="bottom", margin=0.035,
               outline=3, outlineColor="#000000")]
    return out + [cmd("captions.add", track="C1", text=c["text"], seconds=c["start"],
                      durationSeconds=round((c["dur_f"] - 2) / fps, 6)) for c in plan["captions"]]


def interchange(film: Film, fc: FilmCraft) -> None:
    """OTIO and FCPXML beside the project, so other editors can open the cut (clip names carry the beat ids)."""
    fc("11-interchange", [cmd("file.exportOtio", path=str(film.out / f"{film.name}.otio")),
                          cmd("file.exportFcpxml", path=str(film.out / f"{film.name}.fcpxml"))])


def frames_to_ticks(film: Film):
    fps = film.fmt["fps"]
    return lambda frames: frames * TICKS // fps  # frames to FilmCraft ticks, exact


def build(film: Film, plan: dict, music: str | None) -> dict:
    """Assemble the project from scratch; return its beats (id, kind, class, track, FilmCraft clip, frames) and
    the FilmCraft version, for the manifest."""
    film.out.mkdir(exist_ok=True)
    project = project_path(film)
    fc = FilmCraft(film, project)
    caps = check_capabilities(fc.cli)
    if project.exists():
        keep = film.out / "versions" / f"{film.name}-{time.strftime('%Y%m%d-%H%M%S')}.fcproj"
        keep.parent.mkdir(exist_ok=True)
        shutil.move(project, keep)
        print(f"  previous project kept as {keep.relative_to(film.root)}")
    w, h, fps = film.fmt["width"], film.fmt["height"], film.fmt["fps"]
    ft = frames_to_ticks(film)
    fc("01-create", [cmd("file.newProject", name=film.board["title"]),
                     cmd("file.newSequence", name=film.board["title"], width=w, height=h, fps=fps,
                         sampleRate=48000, video=3, audio=2)], create=True)
    beats = intended(film, plan, music)
    paths = sorted({b["path"] for b in beats})
    items = dict(zip(paths, fc("02-import", [cmd("file.import", paths=paths)])[0]["items"]))
    for b, res in zip(beats, fc("03-place", place_cmds(beats, items, ft))):
        b["clip"], b["item"] = res["clips"][0], items[b["path"]]
    motion = motion_cmds(film, beats, [b for b in beats if b["track"] == "V1"], ft)
    if motion:
        fc("04-motion-transitions", motion)
    if music:
        fc("05-mix", [cmd("timeline.setTrack", track="A2", volumeDb=film.board["music"]["volumeDb"])])
    beats += make_notes(film, fc, plan["notes"], ft)
    if film.board["captions"]["mode"] != "none" and plan["captions"]:
        fc("07-captions", caption_cmds(film, plan))
        fc("08-export-srt", [cmd("captions.export", path=str(film.out / f"{film.name}.srt"), track="C1")])
    legible(film, fc, beats, plan, ft)
    interchange(film, fc)
    for b in beats:
        b.pop("_entry")
    print(f"  FilmCraft project: {project.relative_to(film.root)} ({len(beats)} beats; {caps['version']})")
    return {"beats": beats, "filmcraft": caps}


def legible(film: Film, fc: FilmCraft, beats: list[dict], plan: dict, ft) -> None:
    """Make the project readable: clip names with beat ids, colours by kind, named tracks, a marker per
    scene, the editable promise at frame 0, and a bin per kind of media."""
    edits = name_cmds(film, beats)
    edits += [cmd("timeline.setTrack", track=t, name=n) for t, n in TRACKS.items()]
    edits.append(cmd("markers.add", target="program", time=0, name="Showrig project", color="Mango",
                     comment=PROMISE, durationFrames=1))
    scenes = {s["id"]: s for s in film.board["scenes"]}
    spans: dict[str, list[int]] = {}
    for e in plan["video"]:
        lo, hi = spans.get(e["scene"], [e["start_f"], e["start_f"] + e["dur_f"]])
        spans[e["scene"]] = [min(lo, e["start_f"]), max(hi, e["start_f"] + e["dur_f"])]
    for sid, (lo, hi) in spans.items():
        scene = scenes.get(sid, {"kind": "credits", "title": "Credits", "lines": []})
        mine = [b for b in beats if b["scene"] == sid]
        comment = "\n".join([f"scene {sid} ({scene['kind']})", *[f"says: {line}" for line in scene.get("lines", [])],
                             *[f"{b['id']}: {b['kind']}, {b['class']}" for b in mine]])
        edits.append(cmd("markers.add", target="program", time=ft(lo), name=scene.get("title") or sid,
                         comment=comment, color=SCENE_COLORS.get(scene["kind"], "Forest"), durationFrames=hi - lo))
    fc("09-legible", edits)
    kinds_by_item: dict[str, set] = {}
    for b in beats:
        if b["item"] is not None:
            kinds_by_item.setdefault(BINS[b["kind"]], set()).add(b["item"])
    names = [*sorted(kinds_by_item), "Alternates"]
    bins = fc("10-bins", [cmd("file.newBin", name=n) for n in names])
    fc("10-bins-fill", [cmd("project.moveToBin", items=sorted(kinds_by_item[n]), bin=r["bin"])
                        for n, r in zip(names, bins) if n in kinds_by_item])


def render(film: Film, out=None) -> None:
    project = project_path(film)
    if not project.exists():
        raise SystemExit(f"{project} not found; run `showrig make` first")
    out = out or film.out / f"{film.name}.mp4"
    pixels = film.fmt["width"] * film.fmt["height"] * film.fmt["fps"]
    settings = {"hardwareEncoding": "auto", "burnCaptions": film.board["captions"]["mode"] == "burn",
                "bitrateKbps": max(8000, round(24000 * pixels / (1920 * 1080 * 60))), "bitrateMode": "vbr1Pass",
                "effects": {"loudness": {"enabled": True, "target_lufs": -16.0, "true_peak_dbtp": -1.0}}}
    t0 = time.time()
    temporary = out.with_name(out.stem + ".rendering.mp4")
    run([tools.filmcraft(), "--project", project, "export", temporary, "--format", "h264", "--settings",
         json.dumps(settings)], film.log("render.log"))
    info = probe(temporary)
    if not info["width"] or info["duration"] <= 0:
        raise SystemExit("The renderer did not produce a valid video.")
    temporary.replace(out)
    print(f"  rendered {out.relative_to(film.root) if out.is_relative_to(film.root) else out} "
          f"in {time.time() - t0:.0f}s")
