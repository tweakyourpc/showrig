"""Provenance: where every piece of a film came from, under what licence, and a gate on the unresolved ones.

Supplied media (clips, captured pages, images, recorded voice, a music track) carry an optional
"provenance": {"licence": ..., "credit": ..., "url": ...} in the storyboard. Pieces Showrig makes itself (speech,
titles, backdrops, the 3D stage, the score) are recorded as generated. A supplied piece without a licence is a
FLAG. With "provenance": {"gate": "strict"} at the top of the storyboard (new films get it), a FLAG stops the
final render; drafts still build. out/sources.lock records the result with each file's SHA-256.

  showrig sources FILM                                         list every source and its status
  showrig sources FILM set REF --licence L [--credit C] [--url U]   record a licence (REF from the list)
"""
from __future__ import annotations

import json
import time
from pathlib import Path

from .project import Film
from .receipt import sha256

GENERATED = {
    "voice": "speech generated by Showrig with Kokoro-82M (Apache-2.0); yours to use",
    "titles": "title cards rendered by Showrig with EffectCraft; yours to use",
    "backdrops": "backdrops rendered by Showrig; yours to use",
    "stage": "3D stage rendered by Showrig with Blender; yours to use",
    "music": "score synthesised by Showrig; yours to use",
}
UNKNOWN = {"", "unknown", "unclear", "?"}


def _entry(ref: str, what: str, path: Path | None, prov: dict | None, url: str | None = None) -> dict:
    prov = prov or {}
    licence = (prov.get("licence") or "").strip()
    status = "ok" if licence.lower() not in UNKNOWN else "FLAG"
    return {"ref": ref, "what": what, "path": str(path) if path else None, "url": prov.get("url") or url,
            "licence": licence or None, "credit": prov.get("credit"), "status": status}


def collect(film: Film) -> list[dict]:
    """Every supplied source, by the beat id it feeds, plus what Showrig generates."""
    board, out = film.board, []
    for scene in film.board["scenes"]:
        sid = scene["id"]
        for n, shot in enumerate(scene.get("shots", []), 1):
            if shot.get("file"):
                out.append(_entry(f"{sid}/shot{n}", "clip", film.asset(shot["file"]), shot.get("provenance")))
            elif shot.get("capture"):
                url = shot["capture"]["url"]
                local = "://" not in url or url.startswith("file://")
                out.append(_entry(f"{sid}/shot{n}", "captured page", film.asset(url.removeprefix("file://"))
                                  if local else None, shot.get("provenance"), None if local else url))
        if (scene.get("image") or {}).get("file"):
            out.append(_entry(f"{sid}/image", "image", film.asset(scene["image"]["file"]),
                              scene["image"].get("provenance")))
        if board["voice"]["source"] == "files":
            for n, rec in enumerate(scene.get("voice") or [], 1):
                out.append(_entry(f"{sid}/voice{n}", "recorded voice", film.asset(rec), scene.get("voiceProvenance")))
    if board["music"]["source"] == "file" and board["music"].get("file"):
        out.append(_entry("music", "music track", film.asset(board["music"]["file"]), board["music"].get("provenance")))
    made = [("titles", board["style"]["titles"] != "none"), ("backdrops", True),
            ("stage", board["style"]["showcase3d"]), ("voice", board["voice"]["source"] == "tts"),
            ("music", board["music"]["source"] == "procedural")]
    out += [{"ref": f"generated:{k}", "what": k, "path": None, "url": None, "licence": GENERATED[k], "credit": None,
             "status": "ok"} for k, used in made if used]
    return out


def flags(film: Film) -> list[dict]:
    return [s for s in collect(film) if s["status"] != "ok"]


def gate(film: Film, final: bool) -> None:
    """Stop a final render of a strict film while any source is unresolved; otherwise warn."""
    bad = flags(film)
    if not bad:
        return
    strict = (film.board.get("provenance") or {}).get("gate") == "strict"
    lines = [f"  FLAG {s['ref']}: {s['what']} {Path(s['path']).name if s['path'] else s['url']} has no licence"
             for s in bad]
    hint = f"  record one with: showrig sources {film.root} set REF --licence NAME [--credit TEXT] [--url URL]"
    if strict and final:
        raise SystemExit("rights not resolved; the final render is blocked (a --draft still builds):\n" +
                         "\n".join(lines) + "\n" + hint)
    print("warning: sources without a licence (" + ("draft build" if strict else "not enforced for this film") +
          "):\n" + "\n".join(lines))


def write_lock(film: Film) -> Path:
    entries = collect(film)
    for s in entries:
        if s["path"] and Path(s["path"]).exists():
            s["sha256"] = sha256(Path(s["path"]))
            s["path"] = Path(s["path"]).relative_to(film.root).as_posix() if Path(s["path"]).is_relative_to(film.root) \
                else s["path"]
    lock = film.out / "sources.lock"
    film.out.mkdir(exist_ok=True)
    lock.write_text(json.dumps({"schema": 1, "kind": "showrig-sources", "created": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
                                "gate": (film.board.get("provenance") or {}).get("gate", "warn"),
                                "flags": sum(s["status"] != "ok" for s in entries), "sources": entries}, indent=1) + "\n")
    return lock


def owner(film: Film, ref: str) -> dict:
    """The storyboard object whose "provenance" a REF sets."""
    if ref == "music":
        return film.board["music"]
    sid, _, role = ref.partition("/")
    scene = next((s for s in film.board["scenes"] if s["id"] == sid), None)
    if scene is None:
        raise SystemExit(f"no scene {sid!r} (see: showrig sources FILM)")
    if role.startswith("shot") and role[4:].isdigit() and 0 < int(role[4:]) <= len(scene.get("shots", [])):
        return scene["shots"][int(role[4:]) - 1]
    if role == "image" and scene.get("image"):
        return scene["image"]
    if role.startswith("voice"):
        return {"__voice__": scene}
    raise SystemExit(f"{ref} is not a supplied source (see: showrig sources FILM)")


def set_licence(film: Film, ref: str, licence: str, credit: str | None, url: str | None) -> None:
    target = owner(film, ref)
    prov = {k: v for k, v in (("licence", licence), ("credit", credit), ("url", url)) if v}
    if "__voice__" in target:
        target["__voice__"]["voiceProvenance"] = prov
    else:
        target["provenance"] = prov
    film.save()


def show(film: Film) -> int:
    entries = collect(film)
    for s in entries:
        name = Path(s["path"]).name if s["path"] else (s["url"] or "")
        print(f"{s['status']:4}  {s['ref']:22} {s['what']:15} {name[:30]:30} {s['licence'] or '-'}"
              f"{'  (' + s['credit'] + ')' if s.get('credit') else ''}")
    n = sum(s["status"] != "ok" for s in entries)
    gate_mode = (film.board.get("provenance") or {}).get("gate", "warn")
    print(f"{len(entries)} sources, {n} flagged; gate: {gate_mode}")
    return 1 if n else 0
